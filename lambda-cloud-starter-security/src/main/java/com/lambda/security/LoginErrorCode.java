package com.lambda.security;

import cn.dev33.satoken.error.SaErrorCode;

/**
 * 登录错误码定义接口
 * <p>
 * 定义Lambda Cloud安全模块中所有登录相关的错误码常量。
 * 继承自Sa-Token的SaErrorCode接口，提供统一的错误码规范。
 * </p>
 *
 * <h3>错误码规范：</h3>
 * <ul>
 *   <li>20000-20099: 登录认证相关错误</li>
 *   <li>错误码采用递增方式分配</li>
 *   <li>每个错误码都有明确的业务含义</li>
 *   <li>便于前端进行错误处理和用户提示</li>
 * </ul>
 *
 * @author Lambda Cloud Team
 * @since 1.0.0
 */
public interface LoginErrorCode extends SaErrorCode {

    /**
     * 登录类型错误
     * <p>
     * 当用户选择的登录方式不被系统支持或配置错误时返回此错误码。
     * 例如：选择了未启用的第三方登录方式。
     * </p>
     */
    int CODE_20000 = 20000;

    /**
     * 账号或密码错误
     * <p>
     * 用户输入的用户名或密码不正确时返回此错误码。
     * 为了安全考虑，不区分是用户名错误还是密码错误。
     * </p>
     */
    int CODE_20001 = 20001;

    /**
     * 账号被锁定
     * <p>
     * 用户账号因多次登录失败或其他安全原因被系统锁定时返回此错误码。
     * 锁定期间用户无法进行登录操作。
     * </p>
     */
    int CODE_20002 = 20002;

    /**
     * 账号已过期
     * <p>
     * 用户账号已超过有效期，无法继续使用时返回此错误码。
     * 需要联系管理员重新激活账号。
     * </p>
     */
    int CODE_20003 = 20003;

    /**
     * 验证码错误
     * <p>
     * 用户输入的验证码与系统生成的验证码不匹配时返回此错误码。
     * 适用于图形验证码、短信验证码等各种验证码类型。
     * </p>
     */
    int CODE_20004 = 20004;

    /**
     * 验证码过期
     * <p>
     * 验证码已超过有效期，无法继续使用时返回此错误码。
     * 用户需要重新获取验证码。
     * </p>
     */
    int CODE_20005 = 20005;

    /**
     * 缺少验证码
     * <p>
     * 请求中未包含验证码参数，无法进行校验。
     * </p>
     */
    int CODE_20006 = 20006;
}
